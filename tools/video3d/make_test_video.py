"""Generate synthetic video with a KNOWN answer, to test feasibility.py.

    python3 make_test_video.py --out /tmp/clips

Writes translate.mp4, rotate.mp4 and static.mp4. Same scene, same texture,
same frame count. Only the camera path differs, and only one of the three can
be reconstructed. If feasibility.py cannot separate these it will not separate
a good arena video from a bad one either.

The scene is a stack of textured planes at different depths. Image motion is
generated by the exact plane-induced homography

    H = K (R - t n^T / d) K^-1

so each clip is geometrically correct rather than approximated:

  translate   R = I, t sideways. H depends on the plane depth d, so near and
              far planes move by different amounts. That difference IS
              parallax, and it is what makes depth recoverable.
  rotate      t = 0. The t n^T / d term vanishes, so every depth shares one
              homography. Frames move a lot and carry no depth whatsoever.
              This is the failure case the arena video must not be.
  static      R = I, t = 0, sensor noise only.
"""

import argparse
import os

import cv2
import numpy as np


def texture(width, height, rng):
    """High-frequency pattern with corners ORB can actually latch onto."""
    image = rng.integers(40, 215, (height, width, 3), dtype=np.uint8)
    image = cv2.GaussianBlur(image, (5, 5), 0)

    for _ in range(width * height // 900):
        x, y = rng.integers(0, width), rng.integers(0, height)
        size = int(rng.integers(6, 26))
        colour = tuple(int(c) for c in rng.integers(0, 256, 3))

        if rng.random() < 0.5:
            cv2.rectangle(image, (x, y), (x + size, y + size), colour, -1)
        else:
            cv2.circle(image, (x, y), size // 2, colour, -1)

    return image


def build_scene(width, height, rng):
    """Planes as (depth_m, canvas_texture, canvas_mask), far to near.

    Textures live on a canvas three times the frame size so that translating
    the camera reveals new content instead of black edges.
    """
    cw, ch = width * 3, height * 3
    planes = []

    # Back wall: fills the frame at every pose.
    planes.append((6.0, texture(cw, ch, rng),
                   np.full((ch, cw), 255, np.uint8)))

    # Foreground boxes. Their combined area is kept well under half the frame:
    # if one plane dominated the keypoints, RANSAC would fit a homography to
    # everything and the parallax measurement would be trivially easy.
    boxes = [(3.0, 0.10, 0.15, 0.30, 0.45),
             (1.6, 0.55, 0.30, 0.32, 0.40),
             (2.2, 0.20, 0.62, 0.35, 0.25)]

    for depth, fx, fy, fw, fh in boxes:
        mask = np.zeros((ch, cw), np.uint8)

        x0 = int((width + fx * width))
        y0 = int((height + fy * height))
        cv2.rectangle(mask, (x0, y0),
                      (x0 + int(fw * width), y0 + int(fh * height)), 255, -1)

        planes.append((depth, texture(cw, ch, rng), mask))

    return planes


def rotation_y(theta):
    c, s = np.cos(theta), np.sin(theta)
    return np.array([[c, 0.0, s], [0.0, 1.0, 0.0], [-s, 0.0, c]])


def render(planes, K, R, t, width, height):
    # Canvas coordinates are frame-0 coordinates shifted by one frame in each
    # axis; this undoes that shift before the plane homography is applied.
    shift = np.array([[1.0, 0.0, -width], [0.0, 1.0, -height], [0.0, 0.0, 1.0]])
    normal = np.array([[0.0, 0.0, 1.0]])
    K_inv = np.linalg.inv(K)

    out = np.zeros((height, width, 3), np.uint8)

    for depth, tex, mask in planes:
        H = K @ (R - (t.reshape(3, 1) @ normal) / depth) @ K_inv
        M = H @ shift

        warped = cv2.warpPerspective(tex, M, (width, height))
        warped_mask = cv2.warpPerspective(mask, M, (width, height))

        out[warped_mask > 127] = warped[warped_mask > 127]

    return out


def write_clip(path, planes, K, poses, width, height, fps, noise, rng):
    writer = cv2.VideoWriter(path, cv2.VideoWriter_fourcc(*"mp4v"), fps,
                             (width, height))

    if not writer.isOpened():
        raise SystemExit(f"cannot open writer for {path}")

    for R, t in poses:
        frame = render(planes, K, R, t, width, height)

        if noise > 0:
            grain = rng.normal(0.0, noise, frame.shape)
            frame = np.clip(frame.astype(np.float32) + grain, 0, 255)
            frame = frame.astype(np.uint8)

        writer.write(frame)

    writer.release()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=".")
    parser.add_argument("--width", type=int, default=640)
    parser.add_argument("--height", type=int, default=480)
    parser.add_argument("--frames", type=int, default=120)
    parser.add_argument("--fps", type=float, default=30.0)
    parser.add_argument("--travel-m", type=float, default=0.9,
                        help="total sideways camera travel in the translate "
                             "clip; the nearest plane sits at 1.6 m")
    parser.add_argument("--turn-deg", type=float, default=14.0,
                        help="total yaw in the rotate clip, picked so the two "
                             "clips show comparable image motion")
    parser.add_argument("--noise", type=float, default=2.0)
    parser.add_argument("--seed", type=int, default=7)

    args = parser.parse_args()

    rng = np.random.default_rng(args.seed)
    width, height = args.width, args.height

    # ~63 degrees horizontal, close to a wide phone lens and to the ESP32-CAM.
    focal = 0.82 * width
    K = np.array([[focal, 0.0, width / 2.0],
                  [0.0, focal, height / 2.0],
                  [0.0, 0.0, 1.0]])

    planes = build_scene(width, height, rng)
    eye = np.eye(3)
    steps = np.linspace(0.0, 1.0, args.frames)

    clips = {
        "translate.mp4": [(eye, np.array([args.travel_m * s, 0.0, 0.0]))
                          for s in steps],
        "rotate.mp4": [(rotation_y(np.radians(args.turn_deg) * s),
                        np.zeros(3)) for s in steps],
        "static.mp4": [(eye, np.zeros(3)) for _ in steps],
    }

    os.makedirs(args.out, exist_ok=True)

    for name, poses in clips.items():
        path = os.path.join(args.out, name)
        write_clip(path, planes, K, poses, width, height, args.fps,
                   args.noise, np.random.default_rng(args.seed))
        print(f"wrote {path}  ({args.frames} frames, {width}x{height})")


if __name__ == "__main__":
    main()
